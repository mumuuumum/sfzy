# ---------------------------------------------------------------- 尾部（法律依据 + 裁判结果）

# 需求③：法院事实的结束位置由尾部标志确定。这里按"强度分层"给一组候选，
# 算法的做法是——先取最强一档里最靠左的候选，再做"上一句是纯法律依据就并进来"
# 的扩展。之所以不一步到位用一个大正则，是因为语料里的尾部写法太散：
#   依照《侵权责任法》第六条之规定，判决……
#   《合同法》、《民事诉讼法》的规定，判决……（没有"依照"）
#   依照劳动法、劳动合同法规定：1、……（没有书名号，甚至没有"判决"二字）

# "本判决""该判决"里的"判决"是名词，不是裁判结果标志，必须排除。代码里用
# `(?<!本)` 之类的前置断言处理，见 segmenter.find_tail_candidate。

TAIL_CITATION_CORE = r"《[^》]{1,80}》(?:[^。；;！？!?《]{0,60}?《[^》]{1,80}》)*"


class TailRule(NamedTuple):
    """一条尾部候选规则。`strength` 决定候选的优先级（强档优先）。"""

    name: str
    pattern: Pattern[str]
    strength: Strength
    #: True 表示命中后还要把起点往前扩到"法律依据从句"的开头（见 segmenter）。
    extend_back: bool = False
    #: True 表示"引用串到裁判结果动词之间不能夹说理词"（见 segmenter._gap_is_citation_like）。
    #: 没有这道闸，"依据《民事诉讼法》第六十四条之规定，原告……，本院予以支持，
    #: 驳回其余诉讼请求"这种**说理里的驳回**会被当成尾部。
    citation_gap: bool = False


TAIL_RULES: Tuple[TailRule, ...] = (
    # 最典型："依照/依据/根据《……》（可多部法律）……判决/裁定/驳回/如下"
    TailRule(
        "尾部:法律依据+裁判结果",
        re.compile(
            r"(?:依照|依据|根据|按照|参照|依|据)\s*"
            + TAIL_CITATION_CORE
            + r"[^。；;！？!?]{0,60}?(?:判决|裁定|驳回|如下)"
        ),
        Strength.STRONG,
        citation_gap=True,
    ),
    # "判决如下：""裁定如下："——本身没有法律依据，但前面一句/半句往往就是，
    # 用 extend_back 把"依照《……》之规定，"一起并进来。
    TailRule(
        "尾部:判决如下",
        re.compile(r"(?<!本)(?<!该)(?:判决|裁定)\s*如下"),
        Strength.STRONG,
        extend_back=True,
    ),
    # 没有引导动词："《合同法》、《民事诉讼法》的规定，判决……"
    TailRule(
        "尾部:书名号+规定+裁判结果",
        re.compile(
            TAIL_CITATION_CORE
            + r"[^。；;！？!?]{0,20}?(?:之规定|的规定|规定|的有关规定)[，,]?\s*(?:判决|裁定|驳回|如下)"
        ),
        Strength.MEDIUM,
        extend_back=True,
        citation_gap=True,
    ),
    # "《中华人民共和国侵权责任法》……《解释》判决，被告给付……"
    TailRule(
        "尾部:书名号+裁判结果",
        re.compile(TAIL_CITATION_CORE + r"[^。；;！？!?]{0,40}?(?:判决|裁定|驳回)"),
        Strength.MEDIUM,
        extend_back=True,
        citation_gap=True,
    ),
    # "依照劳动法、劳动合同法规定：1、……"（点名单行法、无书名号、无"判决"）
    TailRule(
        "尾部:法律依据从句",
        re.compile(
            r"(?:依照|依据|根据|按照|参照|依)[^。；;！？!?《]{0,40}?(?:规定|法律|法条|解释)\s*"
            r"(?:[：:]|[，,]\s*(?:判决|裁定|驳回|如下))"
        ),
        Strength.MEDIUM,
        extend_back=True,
    ),
    # 兜底："据此/为此/因此/综上/故……判决/裁定/驳回……"（无法律依据引用）
    TailRule(
        "尾部:无法律依据的裁判结果",
        re.compile(r"(?:据此|为此|因此|因而|综上(?:所述)?|故)[^。；;！？!?]{0,40}?(?:判决|裁定|驳回)"),
        Strength.WEAK,
    ),
    # 最弱兜底：结尾只有一串法律依据、连"判决/驳回"都没有（摘要被写残或本就省略）。
    # 只在没有任何更强候选时才会被选中，且只给 low 置信度。
    TailRule(
        "尾部:仅法律依据(弱)",
        re.compile(r"(?:依照|依据|根据|按照|参照|依|据)\s*" + TAIL_CITATION_CORE),
        Strength.WEAK,
    ),
)


#: 只用来做"这段文字里有没有裁判结果"的存在性检查（不用于定位）。
RESULT_MARKER = re.compile(r"(?<!本)(?<!该)(?:判决|裁定|驳回)")


# ---------------------------------------------------------------- 弱信号词表

#: 诉请方向的动词。"默认第二句"之后如果这句话里一个都没有，说明它更像背景或
#: 事实，算法会继续往后看一句（见 segmenter.resolve_p_start）。
CLAIM_VERBS = re.compile(
    r"判令|请求|要求|诉请|诉求|主张|赔偿|支付|偿还|归还|返还|给付|承担|停止|排除|"
    r"解除|撤销|确认|履行|分配|分割|继承|退还|补偿|补缴|协助|腾|赔|付|欠"
)

#: 法院叙述语气，分两档。用于"没有强标志时推断法院事实起点"（需求②的最后一句）。
#:
#: 判分方式见 segmenter._court_like_score：**一个强语素就基本能说明这是法院在说话**，
#: 弱语素则要攒够若干个才算数——单个"合法""责任"在被告答辩里也常见，不能一见就下刀。
COURT_TONE_STRONG = re.compile(
    r"本院|法院|经查|查明|认定|证据|合法有效|有效合同|予以支持|不予支持|不予采信|"
    r"本院认为|法院认为|符合规定|符合法律规定|并无不当|缺乏法律依据|于法有据|"
    r"据此|综上|酌情|应当按照|应当承担|原告未|被告未|故"
)
COURT_TONE_WEAK = re.compile(
    r"合法|有效|无效|违约|过错|责任|赔偿|侵权|应当|应予|支持|采信|驳回|"
    r"事实清楚|缺乏事实|不应支持|不予采纳|不予确认|相一致|依据|不支持"
)
#: 两档的并集（存在性检查用）。
COURT_TONE = re.compile(COURT_TONE_STRONG.pattern + r"|" + COURT_TONE_WEAK.pattern)

#: 说理语气。"纯法律依据从句"里出现这些词，说明它已经混进了说理，扩展要停下。
REASONING_TONE = re.compile(
    r"本院认为|法院认为|查明|证据|辩称|答辩|诉请|诉求|诉讼请求|主张|应予支持|"
    r"不予支持|不予采信|酌情|过错|责任|应当承担|构成违约|合法有效"
)

#: 引用串与裁判结果动词之间**不允许**出现的说理词。用于 `citation_gap` 校验：
#: 只允许"第X条、第X款、及、《……》"这类引用延续符，一旦夹进"原告/被告/辩称/
#: 诉讼请求/予以支持"，说明这个"驳回"是说理里的，不是尾部（需求③点名的坑）。
_CITATION_GAP_FORBIDDEN = re.compile(
    r"原告|被告|第三人|辩称|答辩|诉请|诉求|诉讼请求|主张|请求|予以支持|不予支持|"
    r"应予支持|本院认为|法院认为|故|因此|据此|综上|但|因|应承担"
)


def gap_is_citation_like(gap: str) -> bool:
    """判断"引用串到裁判结果动词"之间那一段是不是纯引用延续。"""

    return not _CITATION_GAP_FORBIDDEN.search(gap or "")

#: 尾部之后的收尾句（迟延履行利息等）。这些句子即使带"依照《……》之规定"，
#: 也不算（新的）法律依据段，避免把尾部起点往后推。
TAIL_AFTERMATH = re.compile(
    r"本判决生效|未按本判决指定的?期间|加倍支付迟延履行期间的债务利息|迟延履行金|"
    r"案件受理费|诉讼费.{0,10}由|如不服本判决|上诉于|本判决为终审判决"
)


