"""三要素切分器用到的全部正则 / 词表。

============================ 为什么单独一个文件 ============================
切分器的正确性几乎全部押在这些正则上，而它们又是要**反复对着真实语料调**的。
把词表和算法分开放，改一个标志时不用在几百行控制流里找它藏在哪；报告工具也
可以直接 import 这份词表，统计"哪个标志真正起了作用"。

============================ 强 / 弱 两档 ============================
每条标志都带一个强度档位（`Strength`）：

  * STRONG —— 出现即可锚定边界，不依赖上下文；
  * MEDIUM —— 需要顺序校验或句边界辅助（例如"经查"既是法院叙述，也可能被
    被告一方复述）；
  * WEAK   —— 只用来兜底，命中后边界记 medium/low 置信度。

这个分档直接对应需求里的"强特征优先、顺序校验、弱特征补充"：算法先拿 STRONG
锚，锚不上再逐级放低。**弱标志永远不会覆盖强标志定下来的边界。**

============================ 关于空白字符 ============================
所有正则都容忍标志内部的空白（`\\s*`），因为两份摘要来源不同：人工摘要里
没有多余空白，而 GRPO 采样出来的候选摘要可能带空格、换行（例如"被告 辩称"）。
切分出来的偏移量始终指向**原文**，不做任何规范化，保证 `text[start:end]` 能
直接还原切片。
"""

from __future__ import annotations

import re
from enum import Enum
from typing import NamedTuple, Pattern, Tuple


class Strength(str, Enum):
    """标志强度。枚举值就是写进结果里的字符串，便于 JSON 化。"""

    STRONG = "strong"
    MEDIUM = "medium"
    WEAK = "weak"


class MarkerRule(NamedTuple):
    """一条标志规则：名字（写进识别来源）、正则、强度。"""

    name: str
    pattern: Pattern[str]
    strength: Strength


def _rule(name: str, pattern: str, strength: Strength) -> MarkerRule:
    return MarkerRule(name, re.compile(pattern), strength)


