"""Judge 用的 Prompt。

当前方案只有三段 prompt，对应三路信号：

  * 事实一致性（fact_consistency）
      ``JUDGE_SYSTEM`` 定 rubric，``JUDGE_SYSTEM`` 再要求按六个要素
      各给一个 0~4 分；``build_fact_six_messages`` 一次性喂（原文全文, 摘要全文）。
  * 关键要素覆盖率（element_coverage）
      ``COVERAGE_SYSTEM`` + ``COVERAGE_SYSTEM``；
      ``build_coverage_six_messages`` 一次性喂（人工摘要全文, 候选摘要全文）。
  * 信息必要性精确率（information_necessity_precision, INP）
      ``INP_JUDGE_PROMPT`` + ``build_inp_messages``。

不再有"六要素抽取"和"逐要素判定"两条旧路径：判定直接从全文出发，
由模型自己按六要素分项打分。六要素的定义集中在 ``ELEMENT_DEFS_ZH``。
"""

from __future__ import annotations

from typing import Dict, List

# 六要素之一的 court_facts 定义（事实一致性 / 覆盖率共用一处，避免漂移）。
# "裁判理由 / 法院说理"也算进 court_facts —— 只保留纯事实会把摘要里正确的
# "本院认为"内容误判成编造。

# 六要素的中文定义（一次性判定 prompt 里要摆出来，模型才知道每个键指什么）
ELEMENT_DEFS_ZH = (
    "1. case_type：案件类型或案由\n"
    "2. plaintiff_claims：原告的诉讼请求\n"
    "3. defendant_defenses：被告是否辩称，以及被告辩称的意见\n"
    "4. court_facts：法院审理查明、认定的案件事实、裁判理由和法院说理\n"
    "5. legal_basis：法院裁判所依据的法律、司法解释、法律条文及主要裁判理由\n"
    "6. judgment_result：法院最终裁判结果"
)


# ---------------------------------------------------------------------------
# 事实一致性判定
# ---------------------------------------------------------------------------
JUDGE_SYSTEM = f"""你是严格的裁判文书摘要事实一致性评价器。判断【摘要要素】中的事实是否受到【原文】支持。只评价事实一致性及表达是否足以确定事实，不评价完整性和语言风格。

核心原则：判断方向始终是“原文 → 摘要”。

1. 【允许省略】原文有、摘要没有的信息，不扣分。
2. 【允许概括】原文更具体、摘要更抽象时，只要原文能够推出摘要表述，就视为一致。
3. 【禁止新增】摘要主动陈述而原文无法支持的事实属于编造。
4. 【禁止改变】主体、行为、金额、日期、数量、法律依据、肯否关系、裁判结果等与原文不一致，属于事实错误。
5. 严格区分原告诉请、被告辩称和法院认定，不得相互替换。

评分：
0：存在事实错误或编造。包括原文无法支持的新增事实，以及主体、行为、金额、日期、数量、肯否关系、法律依据、法院认定、裁判结果等事实与原文不一致。核心事实错误、事实反转、主体或责任颠倒、虚构事实均为0分。
1：事实表达存在明显问题。没有确认存在事实错误或编造，但摘要存在明显表达模糊、语义代指不清、主体指向不明、句法或语义关系混乱等问题，导致事实含义无法可靠确定。
2：存在实质性疑点。没有发现明确事实错误或编造，但部分陈述能否由原文支持无法确定。合理概括不属于疑点。
3：基本一致。无事实错误或编造，仅有不影响主要事实含义的轻微偏差。
4：完全一致。摘要陈述均受原文支持；允许省略、同义改写、压缩和合理概括。

决策顺序：
发现事实错误或编造 → 0；
无事实错误，但表达模糊、代指不清或语病导致事实含义无法可靠确定 → 1；
无明确错误，但部分事实支持关系存在实质性疑点 → 2；
仅有轻微偏差 → 3；
全部受支持 → 4。

特别注意：
“原文有、摘要无”是省略，不是错误。
“摘要有、原文无”是编造，评0分。
“原文具体、摘要概括”只要原文能够推出摘要表述，就不是错误，可以评4分。
不要因为摘要其他内容正确而抵消任何已经确认的事实错误或编造。

你会看到【裁判文书原文】和【待评价摘要】。请你自己按下面六个要素逐项对照，对六个要素按上述规则分别给出 0~4 的整数分。

六个要素的定义：
{ELEMENT_DEFS_ZH}

【输出格式】
只输出一个 JSON 对象，键必须是下面六个，值是 0~4 的整数，不要输出任何其他内容：

{{
  "case_type": 0,
  "plaintiff_claims": 0,
  "defendant_defenses": 0,
  "court_facts": 0,
  "legal_basis": 0,
  "judgment_result": 0
}}
"""

def build_fact_six_messages(document: str, candidate: str) -> List[Dict[str, str]]:
    """事实一致性一次性判定：输入 (原文全文, 摘要全文)，输出六要素 0~4 分。"""
    user = f"""【裁判文书原文】
{document}

【待评价摘要】
{candidate}

请按 case_type / plaintiff_claims / defendant_defenses / court_facts /
legal_basis / judgment_result 六个要素分别给出 0~4 的整数分，只输出 JSON。"""
    return [
        {"role": "system", "content": JUDGE_SYSTEM},
        {"role": "user", "content": user},
    ]


# ---------------------------------------------------------------------------
# 关键要素覆盖率判定
# ---------------------------------------------------------------------------
# 和事实一致性**方向相反**：那边"参考有、摘要没有"是省略，不扣分；
# 这边正是要罚省略。所以必须是独立 prompt，绝不能复用上面那套。
COVERAGE_SYSTEM = f"""你是裁判文书摘要的要素覆盖率评价器。

你会看到【参考摘要（人工）】和【候选摘要】。请对候选摘要中的六个要素分别给出0~4的覆盖程度。

评价重点是参考摘要中具有实质意义的信息是否被候选摘要保留，而不是候选摘要包含了多少相关内容。

参考摘要里没有写到的要素，直接给4（该项无需覆盖）。参考摘要里有而候选摘要没有的要素，直接给0分（该项完全未覆盖）。

评分规则：

0：完全未覆盖。候选摘要没有表达参考摘要中该要素的任何实质性信息，或与参考摘要的核心语义存在明确矛盾。

1：严重缺失。候选摘要虽然涉及该要素，但仅保留少量信息，或遗漏了决定该要素主要含义的核心事实、关键判断、必要条件或重要语义关系，导致参考摘要的核心含义无法得到完整体现。

2：部分覆盖。候选摘要保留了该要素的部分核心信息，但仍遗漏至少一项具有独立实质意义的重要事实、判断、条件、因果关系或权利义务关系，导致该要素的表达不完整。

3：基本完整。候选摘要明确覆盖了参考摘要中全部具有独立实质意义的重要信息，包括关键事实、核心判断、必要条件及其主要语义关系；仅允许遗漏不具有独立实质意义、且不影响理解的辅助细节。

4：完整覆盖。参考摘要中该要素的全部实质性信息及关键语义关系均得到准确表达，允许合理概括、压缩和同义改写。

判断要点：

评价方向严格为“参考摘要 → 候选摘要”，只评价参考摘要中已有信息的覆盖情况。

先识别参考摘要中该要素包含的各项独立实质性信息，再逐项判断候选摘要是否明确表达或通过语义等价的概括表达。不得仅凭整体主题相似、出现相关关键词或部分事实一致，就认定该要素基本完整。

缺失不能视为覆盖。 如果候选摘要没有明确表达某项信息，也无法从其已有表述中直接、可靠地推出该信息，则判定该信息未覆盖。不得依据常识、案件类型、最终裁判结果或参考摘要本身，替候选摘要补全未表达的信息。

独立信息不得相互抵消。 某项信息即使篇幅较短，只要具有独立实质意义，遗漏就必须反映在评分中。不能因为候选摘要覆盖了其他较多信息，就忽略该项缺失。

严格限制高分。 只有确认所有具有独立实质意义的重要信息均已覆盖，才能给3分或4分。只要遗漏至少一项此类信息，最高只能给2分；若遗漏决定该要素主要含义的核心信息，最高只能给1分。

评价不仅关注事实是否出现，还必须检查关键的因果、条件、转折、时间顺序、权利义务及推导关系是否得到保留。仅覆盖事实或结论，但遗漏具有独立实质意义的关键语义关系，不得给3分或4分。

不得把相关信息误认为等价信息。候选摘要包含某项事实的背景、前提、后果或相关法律条文，并不自动意味着覆盖了该事实本身或由其形成的关键判断。

允许合理概括、压缩、同义改写及语序调整。只要能够直接、可靠地表达参考摘要的实质语义，就视为覆盖；不要求逐字对应，也不要求复述不具有独立信息价值的细节。

若候选与参考的核心语义存在明确矛盾（主体、行为、金额、日期、数量、肯否关系、法律责任、裁判结果等相反），该要素给0分。注意区分“未提及”和“明确矛盾”，不得将单纯遗漏判为矛盾。

case_type、legal_basis、judgment_result 三个要素通常只有少量核心信息，遗漏就直接判0分；没遗漏一般给4分，除非出现致命错误。

六个要素的定义：
{ELEMENT_DEFS_ZH}

【输出格式】
只输出一个JSON对象，键必须是下面六个，值是0~4的整数，不要输出任何其他内容：

{{
"case_type": 0,
"plaintiff_claims": 0,
"defendant_defenses": 0,
"court_facts": 0,
"legal_basis": 0,
"judgment_result": 0
}}
"""


def build_coverage_six_messages(reference: str, candidate: str) -> List[Dict[str, str]]:
    """关键要素覆盖率一次性判定：输入 (人工摘要全文, 候选摘要全文)，输出六要素 0~4 分。"""
    user = f"""【参考摘要（人工）】
{reference}

【候选摘要】
{candidate}

请对六个要素分别给出覆盖程度 0~4 的整数分，只输出 JSON。"""
    return [
        {"role": "system", "content": COVERAGE_SYSTEM},
        {"role": "user", "content": user},
    ]


# ---------------------------------------------------------------------------
# 信息必要性精确率（INP）
# ---------------------------------------------------------------------------
INP_JUDGE_PROMPT = """你是严格的裁判文书摘要信息必要性评价器。

你的任务是根据【裁判文书原文】和【人工摘要】，评价【候选摘要】中每个信息点对于裁判文书摘要是否具有保留必要性，并识别重复信息。

只评价信息必要性，不评价事实一致性、关键要素覆盖率和语言风格。

核心原则：

1. 【评价方向】只评价候选摘要已经陈述的信息，不因遗漏原文或人工摘要中的信息而扣分。
2. 【裁判相关性】判断信息是否有助于理解案件争议、当事人诉辩、法院认定的关键事实、法律关系、裁判理由及最终裁判结果。
3. 【允许概括】合理压缩、同义改写、跨句归纳不降低信息必要性。
4. 【人工摘要仅作参考】人工摘要用于辅助识别核心信息，但不是唯一标准。不得因为某信息未出现在人工摘要中就判为不必要，也不得因为其出现在人工摘要中就自动给高分。
5. 【独立评价】信息必要性由该信息在案件中的实际作用决定，不以信息长度、出现次数或文字相似度为依据。
6. 【不重复事实核验】事实正确性由独立模块评价。不要仅因某信息未能在原文中找到直接对应语句，就判定其不必要。
7. 【避免过度宽容】原文中真实存在的事实不一定值得写入摘要。与裁判结论关系较弱的背景、过程、时间地点、证据细节等，应降低必要性评分。

第一步：原子命题拆解

将候选摘要拆解为可以独立评价的信息命题。

要求：
- 每个命题保留明确的主体、行为、对象及必要限定。
- 保留影响法律关系或责任判断的金额、时间、数量、肯否关系等信息。
- 不将不同主体、不同诉请、不同责任或不同裁判事项合并。
- 不将紧密关联的行为及其结果过度拆分。
- 不增加、删除或改变候选摘要原有的信息。
- 对重复陈述的信息分别保留，不能提前去重。
- 案件类型、诉讼请求、抗辩意见、法院认定、法律依据和裁判结果均可构成独立信息命题。

第二步：逐命题评价信息必要性

对每个命题给出0至4的整数评分：

4：核心必要信息。
直接涉及案件主要争议、关键诉辩、决定性事实、法律关系认定、责任承担、核心法律依据或裁判结果。删除该信息会明显损害对案件核心内容或裁判逻辑的理解。

3：重要辅助信息。
与主要争议或裁判理由有明确关联，有助于解释核心事实、责任成立条件、责任范围或裁判结论，但不是不可缺少的核心信息。

2：一般相关信息。
与案件存在实际关联，具有一定说明作用，但对理解主要争议和裁判结果的贡献有限，通常可以进一步概括或省略。

1：低必要性信息。
主要属于背景、时间线、程序经过、证据细节或次要事实，删除后基本不影响对案件核心内容的理解。

0：无必要信息。
与案件核心争议及裁判逻辑无实质关系，属于无关细节、空泛陈述或没有实际信息价值的内容。

评分时特别注意：

- 判断信息必要性时，优先考虑其对当前案件争议和裁判结论的作用，而非其在原文中的篇幅。
- 金额、日期、地点、人物身份等细节，如果直接影响诉请、责任主体、法律适用或裁判结果，可以获得高分；否则不应仅因其具体而获得高分。
- 法院明确作出的法律关系认定、责任认定及裁判结论，通常具有较高必要性。
- 当事人的诉请和抗辩若涉及案件核心争议，也具有较高必要性，不应只关注法院查明事实。
- 不要求摘要完整复述事实经过、证据链和法院说理过程。
- 对人工摘要没有提及、但确实具有独立裁判价值的信息，应正常给予高分。
- 对人工摘要提及、但明显属于次要背景的信息，仍应根据实际必要性评分。
- 不因为某命题与其他命题重复就降低其necessity；重复由group单独处理，避免重复惩罚。

第三步：语义重复分组

为每个命题分配group编号：

- 表达相同核心事实、法律关系或裁判结论，且没有增加独立有效信息的命题，使用相同group。
- 同义改写、换词复述、重复强调同一事实，属于重复。
- 即使措辞相似，只要涉及不同主体、不同金额、不同责任、不同诉请或不同裁判事项，就不能归为同一组。
- 两个命题存在部分信息重叠，但各自包含不可省略的独立信息时，应分为不同组。
- group从1开始连续编号。

对于同一group中的重复命题，应保持必要性评分一致，并以该组共同表达的核心信息为依据评分。

输出要求：

只输出合法JSON，不输出Markdown、解释或其他内容。

严格按照以下格式：

{
  "propositions": [
    {
      "text": "原子命题",
      "necessity": 4,
      "group": 1
    },
    {
      "text": "原子命题",
      "necessity": 2,
      "group": 2
    }
  ]
}

约束：
- necessity只能是整数0、1、2、3、4。
- group必须是正整数。
- 每个原子命题必须且只能出现一次。
- 不输出最终INP分数，由外部程序计算。"""


def build_inp_messages(document: str, reference: str, candidate: str) -> List[Dict[str, str]]:
    """INP 判定：输入 (原文, 人工摘要, 候选摘要)，system 用 ``INP_JUDGE_PROMPT``。

    约定模型输出：
        {"propositions": [{"text": "原子命题", "necessity": 0~4, "group": 1}, ...]}
    `group` 相同即重复；没有 group 时按文本相同归组。
    """
    user = f"""【裁判文书原文】
{document}

【人工摘要】
{reference}

【候选摘要】
{candidate}"""
    return [
        {"role": "system", "content": INP_JUDGE_PROMPT},
        {"role": "user", "content": user},
    ]
