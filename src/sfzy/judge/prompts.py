INP_JUDGE_PROMPT = """你是严格的裁判文书摘要信息必要性评价器。

裁判文书摘要的目的是让读者通过简短文字，大致了解案件主要情况、双方争议、法院主要认定及裁判逻辑，而不是复述案件经过和全部说理。

请以【人工摘要】为主要重要性参照，结合【裁判文书原文】，只评价【候选摘要】中以下三类信息的保留必要性：

1. 原告的诉讼请求（plaintiff_claims）。
2. 被告是否答辩及其具体抗辩意见（defendant_defenses）。
3. 法院查明、认定的事实，以及法院对事实、法律关系和责任承担的分析与说理（court_facts）。

【一、评价范围】

必须先筛选候选摘要中的上述三类信息，再进行拆分和评分。

以下信息一律不评价、不输出：
- 案件类型、案由及单纯的法律关系类别介绍。
- 法律条文、司法解释及法律依据的引用。
- 最终裁判结果及判决主文。

注意区分：
- “原告请求解除合同”属于诉讼请求，应评价。
- “法院认定原告有权解除合同”属于法院说理，应评价。
- “法院判决解除合同”属于裁判结果，不评价。
- “法院认定合同合法有效”属于法院认定，应评价。
- “本案系租赁合同纠纷”属于案件类型，不评价。

只评价候选摘要实际包含的信息，不补充遗漏内容。

【二、命题拆分】

将筛选出的信息拆分为能够独立判断必要性的命题。

- 不同事实、当事人主张、法院认定及独立说理应分别拆分。
- 核心事实与可以独立省略的背景、原因、经过及细节应分别拆分。
- 不机械拆分必要的主体、金额及其他法律意义上的限定。
- 保持原意，不增加、遗漏或改变信息。
- 重复命题分别保留，不提前去重。

【三、信息必要性评价】

以人工摘要为主要参照，判断候选命题是否值得占用简短司法摘要的篇幅。

首先识别人工摘要中三类信息所构成的核心内容与裁判逻辑。

然后逐一判断候选命题：

1. 是否表达了人工摘要中的核心信息，或其合理概括、同义表达？
2. 如果人工摘要没有该信息，它是否补充了理解案件所必需的重要内容？
3. 如果删除该信息，读者是否仍能按照人工摘要呈现的逻辑理解案件主要情况和法院判断？

评分只能使用0、1、2、4：

4：核心必要信息。
属于人工摘要重点保留的主要诉请、实质抗辩、关键事实或法院核心认定；或者虽然人工摘要未提及，但确实补充了不可缺少的关键逻辑节点。删除后会明显损害对案件主要情况或裁判逻辑的理解或摘要的完整性。

2：辅助信息。
与案件有关，能够提供一定补充解释，但不是理解案件核心逻辑所必需。包括具有一定说明价值的补充事实、次要抗辩及附加说理。

1：低必要性信息。
主要属于背景、原因、过程、历史沿革、具体时间地点或其他次要细节。删除后几乎不影响对案件主要情况的理解。

0：无必要信息。
与案件主要情况及裁判逻辑没有实质关系，或者不提供有价值的案件信息。

【四、人工摘要参照规则】

- 人工摘要是信息重要性的主要参照，不是唯一正确答案。
- 优先保留人工摘要所体现的核心事实和裁判逻辑，而不是补充完整的事实经过。
- 人工摘要未提及的信息，不得仅因真实、相关或出现在法院说理中就获得高分。
- 对人工摘要未提及的补充事实、次要抗辩和附加说理，若删除后仍能理解人工摘要的核心逻辑，原则上不超过2分。
- 人工摘要未提及的信息，只有在明显补足关键逻辑缺口时，才能获得4分。
- 人工摘要提及的信息也不自动获得4分；若只是次要背景，仍应给予低分。
- 不因候选摘要遗漏人工摘要中的其他信息而扣分。
- 不评价事实正确性、信息覆盖率或语言风格。
- 对重要性的判断应以信息的实际作用为准，不以文字相似度为准。

【五、重复分组】

为每个命题分配group编号：
- 表达相同信息且没有独立信息增量的命题，使用相同group。
- 具有独立信息价值的命题，使用不同group。
- 同一group的necessity必须相同。
- group从1开始连续编号。
- 不因重复而降低necessity，重复由group单独处理。

【六、输出】

只输出合法JSON，不输出解释或Markdown：

{
  "propositions": [
    {"text": "原子命题", "necessity": 4, "group": 1},
    {"text": "原子命题", "necessity": 2, "group": 2}
  ]
}

约束：
- necessity只能是整数0、1、2、4。
- group必须是正整数。
- 只能输出指定三类信息。
- 每个符合评价范围的信息点必须且只能出现一次。
- 不输出最终INP分数。
- 若没有符合评价范围的信息，输出 
{
  "propositions": [
    {"text": "原子命题", "necessity": 4, "group": 1},
    {"text": "原子命题", "necessity": 2, "group": 2}
  ]
}
"""


def build_inp_messages(document: str, reference: str, candidate: str) -> List[Dict[str, str]]:
    """INP 判定：输入 (原文, 人工摘要, 候选摘要)，system 用 ``INP_JUDGE_PROMPT``。

    约定模型输出：
        {"propositions": [{"text": "原子命题", "necessity": 0~4, "group": 1}, ...]}
    `group` 相同即重复；没有 group 时按文本相同归组。
    """
    user = f"""【裁判文书原文】
{document}

【人工摘要】
{reference}

【候选摘要】
{candidate}"""
    return [
        {"role": "system", "content": INP_JUDGE_PROMPT},
        {"role": "user", "content": user},
    ]


# ---------------------------------------------------------------------------
# 表达效率（EE）
# ---------------------------------------------------------------------------
# ⚠️ 这段 prompt 由使用者自行填写，这里**保持空字符串**，不要代写评价规则。
# 一次调用返回三个维度的 0~4 分：
#   {"semantic_redundancy": 4, "verbal_redundancy": 3, "abstraction_adequacy": 2}
EE_JUDGE_PROMPT = """你是严格的裁判文书摘要信息表达效率评价器。

裁判文书摘要的目的是通过简洁、准确的文字，使读者了解案件基本情况、双方主要争议、法院核心认定及最终裁判结果，而不是复述裁判文书。

请根据【裁判文书原文】和【人工参考摘要】，评价【候选摘要】的信息表达效率。

你需要分别评价以下三个维度，每个维度独立给出0、1、2、3、4五档整数评分，分数越高表示表达效率越好。

## 一、评价范围与基本原则

1. 只评价候选摘要的表达方式，不评价事实一致性、关键要素覆盖率或摘要完整性。
2. 不因候选摘要比人工摘要长、短或措辞不同而直接扣分。
3. 不因候选摘要包含人工摘要未提及的事实而直接扣分。
4. 不因候选摘要遗漏信息而直接加分。信息遗漏由其他指标评价。
5. 允许必要的事实说明、法律关系分析、责任认定及裁判说理。
6. 评价应以是否能够在保留原有实质含义的情况下减少重复、压缩措辞或合理概括为依据，而不是单纯追求更短。
7. 原文用于理解实体身份、法律关系和必要的事实限定；人工摘要仅作为表达方式和抽象粒度的参考，不是唯一正确表达。

## 二、语义冗余（semantic_redundancy）

判断候选摘要是否重复陈述相同或高度重叠的实质信息。

评价规则：

- 同一事实、观点、法律认定或裁判结论被多次陈述，且后续陈述没有提供实质性新信息，属于语义冗余。
- 即使使用不同措辞，只要表达的是相同信息，也应识别重复。
- 同一信息在不同位置反复出现，应根据实际重复程度扣分。
- 原告诉请、被告辩称、法院认定和最终裁判结果属于不同陈述角色，即使内容相似，也不能仅因此认定为重复。
- 事实与基于该事实形成的法律评价、原因与结果、主张与法院回应，不应简单视为重复。
- 必要的主体重申、法律关系说明和消除歧义的表达不属于冗余。

评分：

4：没有明显语义重复，各项陈述均提供独立信息或具有必要的表达功能。

3：存在少量轻微语义重复，但整体信息组织紧凑。

2：存在明显语义重复，部分事实、观点或结论被不必要地重复陈述。

1：存在多处严重语义重复，大量陈述没有增加实质信息。

0：极度重复，大部分内容反复表达相同或高度重叠的信息。

## 三、表达冗余（verbal_redundancy）

判断候选摘要是否存在不必要的词语、句式、套话和低效表达。

评价规则：

- 不必要的重复修饰、冗长铺垫、套话、赘词和低效句式属于表达冗余。
- 可以直接表达的内容被不必要地绕述，属于表达冗余。
- 同一句话中重复出现相同主语、行为或限定，且可以无损合并的，属于表达冗余。
- 正常的法律术语、必要的逻辑连接、准确的责任划分和事实限定不属于表达冗余。
- 不得仅因句子较长、使用正式法律语言或包含多个事实而扣分。
- 不得以牺牲法律含义、主体清晰度或事实准确性为代价追求简短。

评分：

4：措辞凝练，句式清晰，基本不存在可以无损删除或压缩的语言。

3：存在少量赘词、重复修饰或不够精练的句式。

2：存在多处明显啰嗦表达，部分句子可以显著压缩而不损失实质含义。

1：大量使用冗长句式、套话或重复修饰，表达效率较低。

0：表达极度啰嗦，大量文字没有增加有效含义，明显不符合摘要式表达。

## 四、抽象适当性（abstraction_adequacy）

判断候选摘要是否在保持必要事实含义、主体区分和法律关系的前提下，采用适当的抽象层次，而不是不必要地保留原文中的具体实体和细节。

评价规则：

- 当具体姓名可以明确替换为“原告”“被告”“被继承人”等角色称谓，且不会造成主体混淆时，优先使用角色称谓。
- 当完整地址、机构名称、时间、面积、背景经过等细节可以用“案涉房屋”“相关工程”“涉案合同”等概括性表达替代，且不会损失理解案件争议和裁判结论所需的信息时，保留过细的表达可以适当扣分。
- 当多个具体事实可以通过准确的上位概念、法律关系或法院核心认定加以概括，且不改变原意时，合理概括通常优于逐项罗列。
- 不要求删除所有人名、地名、日期、金额和数量。凡是用于区分多个主体、多个标的、确定争议范围、说明法律关系、计算责任或理解裁判结果的具体信息，都应保留。
- 多名原告、被告、继承人或其他主体具有不同主张、责任、继承份额时，不得为了简洁而模糊其区别。
- 金额、比例、期限、份额、关键日期及其他决定裁判结果的限定条件，不应仅为了提高抽象程度而省略。
- 人工摘要可以帮助判断适当的表达粒度，但不能仅因候选摘要比人工摘要具体就扣分。
- 不评价某项独立事实是否值得写入摘要，只评价该事实在已经被陈述的情况下，是否存在不必要的过度具体化。
- 抽象程度并非越高越好；过度概括导致含义模糊或主体不清，也不属于良好的抽象表达。

评分：

4：抽象层次适当，能够合理使用角色称谓、概括性表达及核心法律认定，同时保留必要的具体信息。

3：整体抽象适当，仅存在少量可以进一步概括的姓名、地点或事实细节。

2：存在明显过度具体化，多处保留了本可概括的实体信息或细节，但仍能清楚表达案件含义。

1：大量直接照搬具体实体、背景经过或细节，缺乏必要概括，明显影响摘要表达效率。

0：严重缺乏抽象概括，主要以原始事实细节堆砌的方式表达，明显偏离摘要式表达。

## 五、三个维度的区分

三个维度应独立判断，不得因为某个维度表现较差而自动降低其他维度的评分。

- 重复表达同一事实，主要影响 semantic_redundancy。
- 用冗长措辞表达同一含义，主要影响 verbal_redundancy。
- 不必要地保留具体姓名、地址、背景经过或可概括的细节，主要影响 abstraction_adequacy。
- 如果同一段文字确实同时存在不同类型的问题，可以分别扣分，但必须有各自独立的理由。
- 候选摘要较长不代表三个维度都差；候选摘要较短也不代表三个维度都好。
- 不得将事实错误、信息遗漏或单纯的写作风格差异当作表达效率问题。

## 六、评分要求

请先分别判断三个维度是否存在明确问题，再根据问题的数量、严重程度及对整体表达效率的影响给出评分。

评分时应避免过度苛刻：轻微的措辞差异、正常的法律语言以及合理保留的具体事实，不应导致明显扣分。

只输出合法 JSON，不输出 Markdown，不解释，不添加其他字段。

输出格式严格为：

{
  "semantic_redundancy": 4,
  "verbal_redundancy": 4,
  "abstraction_adequacy": 4
}"""


def build_ee_messages(document: str, reference: str, candidate: str) -> List[Dict[str, str]]:
    """表达效率判定：输入 (原文, 人工参考摘要, 候选摘要)，system 用 ``EE_JUDGE_PROMPT``。

    约定模型输出：
        {"semantic_redundancy": 0~4, "verbal_redundancy": 0~4, "abstraction_adequacy": 0~4}
    """
    user = f"""【裁判文书原文】
{document}

【人工参考摘要】
{reference}

【候选摘要】
{candidate}"""
    return [
        {"role": "system", "content": EE_JUDGE_PROMPT},
        {"role": "user", "content": user},
    ]
