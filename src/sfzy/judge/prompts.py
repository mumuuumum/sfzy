"""Judge 用的 Prompt。

当前方案只有三段 prompt，对应三路信号：

  * 事实一致性（fact_consistency）
      ``JUDGE_SYSTEM`` 定 rubric，``JUDGE_SYSTEM`` 再要求按六个要素
      各给一个 0~4 分；``build_fact_six_messages`` 一次性喂（原文全文, 摘要全文）。
  * 关键要素覆盖率（element_coverage）
      ``COVERAGE_SYSTEM`` + ``COVERAGE_SYSTEM``；
      ``build_coverage_six_messages`` 一次性喂（人工摘要全文, 候选摘要全文）。
      原文只是核对背景，评分口径不变 —— 见 ``COVERAGE_SYSTEM`` 里的说明。
  * 信息必要性精确率（information_necessity_precision, INP）
      ``INP_JUDGE_PROMPT`` + ``build_inp_messages``。

不再有"六要素抽取"和"逐要素判定"两条旧路径：判定直接从全文出发，
由模型自己按六要素分项打分。六要素的定义集中在 ``ELEMENT_DEFS_ZH``。
"""

