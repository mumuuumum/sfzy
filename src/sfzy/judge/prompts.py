# 第三步：针对每个维度，判断候选摘要与人工摘要之间是否存在可感知的表达效率差距，以及差距的程度和影响范围。

# 第四步：根据对应维度的五档标准选择0、1、2、3、4中的一个整数。

# 第五步：检查评分是否符合以下要求：

# - 4分表示与人工摘要几乎一致或更好，而不是仅仅没有发现严重缺陷。
# - 3分表示轻微差距，2分表示明显差距，1分表示显著差距，0分表示极大差距。
# - 不得因为候选摘要更长、更短或包含不同信息而机械调整评分。
# - 不得将信息遗漏视为表达效率提高。
# - 不得将必要的法律事实和裁判说理误判为冗余。
# - 不得为了制造分数差异而强行扣分。
# - 如果不同候选确实存在可感知的表达效率差距，应当按照评分标准如实体现，而不是一律给予4分。

# ## 八、输出要求

# 只输出合法JSON，不输出Markdown，不解释，不添加其他字段。

# 输出格式严格为：

# {
#   "semantic_redundancy": 4,
#   "verbal_redundancy": 4,
#   "abstraction_adequacy": 4
# }
# """


def build_ee_messages(document: str, reference: str, candidate: str) -> List[Dict[str, str]]:
    """表达效率判定：输入 (原文, 人工参考摘要, 候选摘要)，system 用 ``EE_JUDGE_PROMPT``。

    约定模型输出：
        {"semantic_redundancy": 0~4, "verbal_redundancy": 0~4, "abstraction_adequacy": 0~4}
    """
    user = f"""【裁判文书原文】
{document}

【人工参考摘要】
{reference}

【候选摘要】
{candidate}"""
    return [
        {"role": "system", "content": EE_JUDGE_PROMPT},
        {"role": "user", "content": user},
    ]
