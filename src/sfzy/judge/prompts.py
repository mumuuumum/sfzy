"""两段 Prompt，逐字照搬需求原文。

不改措辞是有意的：这套 Prompt 是要被验证的对象，先按原样跑出基线，
改动才有对照。要改就新开一个版本号，别在原文上打补丁 —— 否则
"改了哪一句让效果变好"永远说不清。
"""

from __future__ import annotations

from typing import Dict, List

from sfzy.judge.schema import ELEMENT_ZH

# ---------------------------------------------------------------------------
# 六要素提取（需求第二节）
# ---------------------------------------------------------------------------
EXTRACT_SYSTEM = """你是一个裁判文书信息抽取模型。

你的任务是从输入文本中提取案件的六个核心要素。

只能根据输入文本提取信息，不得补充、猜测或推断文本中没有明确表达的事实。

六个要素分别为：

1. case_type：案件类型或案由
2. plaintiff_claims：原告的诉讼请求
3. defendant_defenses：被告的辩称、抗辩意见
4. court_facts：法院审理查明、认定的案件事实
5. legal_basis：法院裁判所依据的法律、司法解释、法律条文及主要裁判理由
6. judgment_result：法院最终裁判结果

特别注意区分：

- 原告“主张”的事实；
- 被告“辩称”的事实；
- 法院最终“查明或认定”的事实。

不得将当事人的单方主张直接视为法院认定事实。

尽量保留对案件具有事实意义的信息，包括主体、行为、金额、日期、数量、比例、法律条文以及裁判结果。

如果某个要素在输入文本中不存在，返回空字符串。

只输出合法 JSON，不输出 Markdown，不解释。

输出格式严格为：

{
  "case_type": "",
  "plaintiff_claims": "",
  "defendant_defenses": "",
  "court_facts": "",
  "legal_basis": "",
  "judgment_result": ""
}"""


def build_extract_messages(text: str) -> List[Dict[str, str]]:
    return [
        {"role": "system", "content": EXTRACT_SYSTEM},
        {"role": "user", "content": text},
    ]


# ---------------------------------------------------------------------------
# 事实一致性判定（需求第三节）
# ---------------------------------------------------------------------------
JUDGE_SYSTEM = """你是一名裁判文书摘要事实一致性评价器。

你的任务不是评价语言质量，也不是评价摘要是否足够详细，而是判断“待评价摘要要素”中陈述的事实是否能够得到“裁判文书原文要素”的支持。

你必须严格依据提供的原文要素进行判断。

需要特别检查：

- 人物或主体是否一致；
- 原告、被告及其他主体的身份和行为是否被混淆；
- 行为、事件及其对象是否一致；
- 金额、日期、数量、比例、期限是否一致；
- 肯定、否定关系是否发生变化；
- 原告的诉讼请求是否被错误描述；
- 被告的抗辩是否被错误描述；
- 法院认定事实是否被错误描述；
- 法律依据、法律名称、条文是否被错误描述；
- 裁判结果中的支持、驳回、赔偿、支付、返还、承担责任等是否被错误描述。

重要评分原则：

第一，摘要允许压缩和省略。

如果原文包含 A、B、C 三项事实，而摘要只陈述 A，只要摘要对 A 的陈述正确，不得仅因为没有提到 B、C 而降低“事实一致性”评分。

第二，省略和错误必须严格区分。

“没有提到某个事实”属于省略；
“提到了这个事实但描述错误”属于事实错误。

第三，概括允许存在。

例如：

原文：
“被告于2023年3月1日向原告偿还借款人民币100000元。”

摘要：
“被告曾偿还部分借款。”

这种概括可以认为事实一致。

但是：

摘要：
“被告偿还借款人民币200000元。”

属于事实不一致。

第四，不允许使用常识补充原文。

只判断摘要中的陈述能否从给出的原文要素中得到支持。

第五，摘要新增了原文无法支持的重要事实，也属于事实一致性问题。

请使用以下五档评分：

4 = 完全一致
摘要中的事实均能够由原文支持。允许合理概括、改写和省略细节，不存在实质性事实错误。

3 = 基本一致
核心事实正确，但存在非常轻微的不准确、表述范围扩大、细节偏差或不影响主要含义的问题。

2 = 部分一致
部分内容能够得到原文支持。

1 = 严重不一致
存在重要主体、行为、金额、法律依据、案件事实等方面的严重错误，但仍有少量内容与原文一致。

0 = 核心事实矛盾
摘要的核心陈述与原文明显矛盾，尤其是裁判结果被反转、关键主体关系颠倒、核心金额或主要案件事实发生严重错误。

只输出一个整数：

0
1
2
3
或
4

不得输出任何其他文字。"""


# ---------------------------------------------------------------------------
# 少样本版判定 Prompt
# ---------------------------------------------------------------------------
# 为什么需要它：规范 Prompt 是给"能读懂一长串细则"的模型写的。实测
#
#   Qwen2.5-0.5B  三套提示词下都是常量输出（4 / 3 / 1），提示词无从下手
#   Qwen2.5-1.5B  10 条探针答对 6 条，**答案随内容变化**（pmax 0.45~1.00），
#                 但错在最要命的四条上：合理概括判 0、金额写错判 2、
#                 主体颠倒判 4、编造事实判 4
#
# 后者是"能力有、行为没锚定"，不是"能力不足" —— 这种情况示例比细则管用。
# 五个示例逐一对应上面四条失败模式，外加一条结果反转。
#
# 示例里的分数刻意只用 4 / 1 / 0 三档：五档的细分对 1.5B 太细，
# 能把"对"和"错"分开就够（探针判据也是 ≥3 / ≤1）。
JUDGE_SYSTEM_FEWSHOT = """你是裁判文书摘要事实一致性评价器。判断摘要里陈述的事实能否被原文支持。

评分：
4 = 摘要的陈述都能被原文支持。允许省略细节、换词、合理概括。
1 = 摘要里有明显错误（金额、主体、时间、行为与原文不符），或加了原文没有的内容。
0 = 摘要的核心结论与原文相反。

关键：摘要没提到的内容不算错；摘要自己加上原文没有的内容算错。

示例1（省略加概括，正确）
原文：被告于2019年3月1日向原告偿还借款人民币100000元。
摘要：被告曾偿还部分借款。
输出 4

示例2（金额写错）
原文：判决被告偿还原告借款本金50000元。
摘要：判决被告偿还原告借款本金90000元。
输出 1

示例3（主体颠倒）
原文：判决被告偿还原告借款本金50000元。
摘要：判决原告偿还被告借款本金50000元。
输出 0

示例4（加了原文没有的内容）
原文：被告向原告借款50000元，至今未还。
摘要：被告向原告借款50000元，至今未还，双方还约定由被告支付违约金20000元。
输出 1

示例5（结果反转）
原文：判决被告偿还原告借款本金50000元。
摘要：判决驳回原告的诉讼请求。
输出 0

现在判断下面这一例，只输出一个整数（0/1/2/3/4）。"""

JUDGE_VARIANTS = {"spec": JUDGE_SYSTEM, "fewshot": JUDGE_SYSTEM_FEWSHOT}


def build_judge_messages(
    element_name: str, document_element: str, candidate_element: str,
    variant: str = "spec",
) -> List[Dict[str, str]]:
    """`element_name` 用英文键名，但正文里给出中文名 —— 需求里就是这么写的。"""
    if variant not in JUDGE_VARIANTS:
        raise ValueError(f"未知的判定 Prompt 版本：{variant}（可选 {list(JUDGE_VARIANTS)}）")
    zh = ELEMENT_ZH.get(element_name, element_name)

    if variant == "fewshot":
        # **user 消息必须和示例里的格式一致。**
        # 第一版少样本没生效就是这个原因：示例写的是"原文：…/摘要：…"，
        # 而真实调用用的是规范 prompt 那套"裁判文书原文要素：…"的冗长格式，
        # 格式对不上，模型学到的是另一个任务的行为，于是坏样本全卡在 2 分。
        user = (
            f"要素：{zh}\n"
            f"原文：{document_element}\n"
            f"摘要：{candidate_element}\n"
            "只输出一个整数（0/1/2/3/4）。"
        )
        return [
            {"role": "system", "content": JUDGE_VARIANTS[variant]},
            {"role": "user", "content": user},
        ]

    user = f"""当前评价要素类型：
{zh}（{element_name}）

裁判文书原文要素：
{document_element}

待评价摘要要素：
{candidate_element}

    请判断待评价摘要要素与裁判文书原文要素的事实一致性。"""
    return [
        {"role": "system", "content": JUDGE_VARIANTS[variant]},
        {"role": "user", "content": user},
    ]
