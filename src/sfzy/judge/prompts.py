"""Judge 用的 Prompt。

当前方案有四段 prompt，对应四路信号：

  * 事实一致性（fact_consistency）
      ``JUDGE_SYSTEM`` 定 rubric：一次判定输出
      ``has_factual_error``（事实硬门控）+ ``fact_consistency_score``（整体 0~4）
      + ``error_reason``；``build_fact_messages`` 一次性喂（原文全文, 摘要全文）。
  * 关键要素覆盖率（element_coverage）
      ``COVERAGE_SYSTEM`` + ``COVERAGE_SYSTEM``；
      ``build_coverage_six_messages`` 一次性喂（人工摘要全文, 候选摘要全文）。
      原文只是核对背景，评分口径不变 —— 见 ``COVERAGE_SYSTEM`` 里的说明。
  * 信息必要性精确率（information_necessity_precision, INP）
      ``INP_JUDGE_PROMPT`` + ``build_inp_messages``。
  * 表达效率（expression_efficiency, EE）
      ``EE_JUDGE_PROMPT`` + ``build_ee_messages``。输入
      (原文, 人工参考摘要, 候选摘要)。

不再有"六要素抽取"和"逐要素判定"两条旧路径：判定直接从全文出发，
由模型自己按六要素分项打分。六要素的定义集中在 ``ELEMENT_DEFS_ZH``。
"""

from __future__ import annotations

from typing import Dict, List

# 六要素之一的 court_facts 定义（事实一致性 / 覆盖率共用一处，避免漂移）。
# "裁判理由 / 法院说理"也算进 court_facts —— 只保留纯事实会把摘要里正确的
# "本院认为"内容误判成编造。

# 六要素的中文定义（一次性判定 prompt 里要摆出来，模型才知道每个键指什么）
ELEMENT_DEFS_ZH = (
    "1. case_type：案件类型或案由\n"
    "2. plaintiff_claims：原告的诉讼请求\n"
    "3. defendant_defenses：被告是否辩称，以及被告辩称的意见\n"
    "4. court_facts：法院审理查明、认定的案件事实、裁判理由和法院说理\n"
    "5. legal_basis：法院裁判所依据的法律、司法解释、法律条文及主要裁判理由\n"
    "6. judgment_result：法院最终裁判结果"
)


# ---------------------------------------------------------------------------
# 事实一致性判定
# ---------------------------------------------------------------------------
JUDGE_SYSTEM = """你是裁判文书摘要事实一致性评价器。

任务是判断【待评价摘要】已陈述的事实是否受到【裁判文书原文】支持，而不是检查摘要是否完整、详细或具有法律文书的精确程度。

请完成三个任务：

**任务一：明确事实错误检测**

输出 `has_factual_error`：

- 0：没有发现能够确定的事实错误或编造。
- 1：摘要和原文之间存在非常严重的对立、彻头彻尾的编造。1必须非常谨慎地给。
- "信息遗漏"、"信息不完整"不能当事实错误，不能给1
- 参考其实与原文原句一致不能给1

**任务二：整体事实一致性评分**

只评价摘要已陈述内容的事实一致性，不评价信息覆盖率、摘要长度或语言风格。

- 4：摘要全部事实陈述受到原文支持，允许省略、概括、压缩和同义改写。
- 3：整体一致，仅存在轻微的不精确表达，不改变关键事实含义。
- 2：部分事实的支持关系存在实质性疑点，但没有确认明确错误。
- 1：存在明显歧义、主体不清或语义关系混乱，导致事实含义难以确定，但没有确认明确错误。
- 0：摘要和原文之间存在非常严重的对立、彻头彻尾的编造。这个分数必须非常谨慎地给。

**任务三：错误原因**

输出 `error_reason`：

- `has_factual_error=0` 时，输出空字符串。
- `has_factual_error=1` 时，必须简洁指出摘要中的错误陈述及其与原文的明确矛盾。
- 不能以信息遗漏、缺少细节、合理概括、可能误导、表达不够严谨等作为触发门控的理由。
- 如果无法指出具体矛盾，必须重新考虑是否真的存在明确错误。
- "信息遗漏"、"信息不完整"不能当事实错误，不能给1
- 参考其实与原文原句一致不能给1

**一致性约束**

- `has_factual_error=1` 时，`fact_consistency_score=0`，`error_reason` 非空。
- `has_factual_error=0` 时，`fact_consistency_score` 为1～4，`error_reason` 为空字符串。
- 事实错误不能被其他正确内容抵消。
- 不确定是否存在错误时，不触发门控。
- 先给has_factual_error，再判断给fact_consistency_score，最后给error_reason。

只输出 JSON：

{
  "has_factual_error": 0,
  "fact_consistency_score": 4,
  "error_reason": ""
}
"""

def build_fact_messages(document: str, candidate: str) -> List[Dict[str, str]]:
    """事实一致性判定：输入 (原文全文, 摘要全文)。

    输出 ``{"has_factual_error": 0/1, "fact_consistency_score": 0~4, "error_reason": str}``
    —— ``has_factual_error`` 是事实硬门控信号，``fact_consistency_score`` 是整体分。
    """
    user = f"""【裁判文书原文】
{document}

【待评价摘要】
{candidate}

请按上述要求输出 JSON（has_factual_error / fact_consistency_score / error_reason），只输出 JSON。"""
    return [
        {"role": "system", "content": JUDGE_SYSTEM},
        {"role": "user", "content": user},
    ]


