"""两段 Prompt，逐字照搬需求原文。

不改措辞是有意的：这套 Prompt 是要被验证的对象，先按原样跑出基线，
改动才有对照。要改就新开一个版本号，别在原文上打补丁 —— 否则
"改了哪一句让效果变好"永远说不清。
"""

from __future__ import annotations

from typing import Dict, List

from sfzy.judge.schema import ELEMENT_ZH

# ---------------------------------------------------------------------------
# 六要素提取（需求第二节）
# ---------------------------------------------------------------------------
EXTRACT_SYSTEM = """你是一个裁判文书信息抽取模型。

你的任务是从输入文本中提取案件的六个核心要素。

只能根据输入文本提取信息，不得补充、猜测或推断文本中没有明确表达的事实。

六个要素分别为：

1. case_type：案件类型或案由
2. plaintiff_claims：原告的诉讼请求
3. defendant_defenses：被告的辩称、抗辩意见
4. court_facts：法院审理查明、认定的案件事实
5. legal_basis：法院裁判所依据的法律、司法解释、法律条文及主要裁判理由
6. judgment_result：法院最终裁判结果

特别注意区分：

- 原告“主张”的事实；
- 被告“辩称”的事实；
- 法院最终“查明或认定”的事实。

不得将当事人的单方主张直接视为法院认定事实。

尽量保留对案件具有事实意义的信息，包括主体、行为、金额、日期、数量、比例、法律条文以及裁判结果。

如果某个要素在输入文本中不存在，返回空字符串。

只输出合法 JSON，不输出 Markdown，不解释。

输出格式严格为：

{
  "case_type": "",
  "plaintiff_claims": "",
  "defendant_defenses": "",
  "court_facts": "",
  "legal_basis": "",
  "judgment_result": ""
}"""


def build_extract_messages(text: str) -> List[Dict[str, str]]:
    return [
        {"role": "system", "content": EXTRACT_SYSTEM},
        {"role": "user", "content": text},
    ]


# ---------------------------------------------------------------------------
# 事实一致性判定（需求第三节）
# ---------------------------------------------------------------------------
JUDGE_SYSTEM = """**你**是一名严格的裁判文书摘要事实一致性评价器。

你的唯一任务是判断“待评价摘要要素”中实际陈述的内容，是否能够得到“裁判文书原文要素”的支持。

你评价的是【事实一致性】，而不是语言质量、摘要完整性或信息覆盖率。

你必须严格依据给出的原文要素进行判断，不得依据常识、法律知识或上下文自行补充原文没有提供的信息。

## 一、基本判断原则

评价时，以“摘要实际陈述了什么”为中心，逐项判断这些陈述是否受到原文支持。

重点检查：

- 人物、机构或其他主体是否一致；
- 原告、被告及其他主体的身份、行为是否发生混淆；
- 行为、事件、对象及其关系是否一致；
- 金额、日期、数量、比例、期限等是否一致；
- 肯定、否定、已经发生、尚未发生等语义是否发生变化；
- 原告的诉讼请求是否被错误描述；
- 被告的辩称或抗辩是否被错误描述；
- 当事人的主张是否被错误写成法院认定的事实；
- 法院查明或认定的事实是否被错误描述；
- 法律名称、法律条文、司法解释以及法律依据是否被错误描述；
- 裁判结果中的支持、驳回、支付、返还、赔偿、承担责任等是否被错误描述；
- 摘要是否新增原文没有明确支持的事实。

## 二、省略不属于事实错误

摘要允许压缩原文，也允许省略部分事实。

如果原文包含 A、B、C 三项事实，而摘要只陈述 A：

只要摘要对 A 的陈述正确，就不能因为摘要没有提到 B、C 而降低事实一致性评分。

因此必须严格区分：

【省略】
原文存在某项事实，但摘要没有提到。

【错误】
摘要主动陈述了某项事实，但该事实与原文不一致。

【无依据新增】
摘要主动陈述了某项事实，但原文无法支持该事实。

本任务只评价事实一致性，因此单纯的“省略”原则上不扣分。

但是“错误”和“无依据新增”必须扣分。

## 三、允许合理概括

摘要不要求逐字复述原文。

只要概括后的语义能够由原文支持，就属于事实一致。

例如：

原文：
“被告于2023年3月1日向原告偿还借款人民币100000元。”

摘要：
“被告曾偿还部分借款。”

该摘要属于合理概括，不应因为省略日期和具体金额而扣分。

但是，如果摘要主动给出了具体信息，则该信息必须准确。

例如：

原文：
“被告偿还借款人民币100000元。”

摘要：
“被告偿还借款人民币200000元。”

摘要主动给出了错误金额，属于明确事实错误。

## 四、严格区分当事人主张与法院认定

裁判文书中的不同信息来源不能互相替换。

例如：

原文：
“被告辩称涉案款项已经全部偿还。”

这只能说明“被告主张已经偿还”，不能说明法院认定该款项已经偿还。

如果摘要写：

“法院查明被告已经全部偿还涉案款项。”

而原文没有法院作出该项认定，则属于事实错误。

同理：

- 原告的主张不能直接写成法院认定事实；
- 被告的辩称不能直接写成法院认定事实；
- 法院认定事实不能错误归属于原告或被告的单方主张。

## 五、评分标准

必须严格按照以下标准选择 0、1、2、3、4 中的一个整数。

### 4分：完全一致

摘要实际陈述的事实均能够从原文得到明确支持。

允许：

- 同义改写；
- 合理概括；
- 压缩表达；
- 省略部分细节；
- 省略原文中的其他事实。

摘要中不存在事实错误，不存在未经原文支持的新增事实，不存在主体、金额、日期、行为、法律依据、裁判结果等方面的实质性偏差。

只要摘要陈述出来的内容全部正确，即使摘要非常简短，也可以得到4分。

### 3分：基本一致，仅存在轻微瑕疵

摘要的事实陈述整体能够得到原文支持，不存在明确的重要事实错误。

但存在轻微的不精确，例如：

- 非关键细节表达略有偏差；
- 概括范围轻微扩大或缩小；
- 时间、行为或关系的描述不够严谨，但没有改变事件的基本性质；
- 存在极轻微、不会改变案件事实理解的语义偏差。

3分与1分的关键区别是：

3分不能存在明确的重要事实错误。

如果已经能够明确指出“摘要说错了一个具有实际意义的事实”，原则上不应评3分。

### 2分：存在实质性疑点或局部无法确认，但尚不能认定存在明确的重要事实错误

摘要整体方向与原文基本相符，但是部分陈述无法从给出的原文中得到充分确认，或者存在较明显的语义扩大、模糊归因、关系表达不严谨等问题。

典型情况包括：

- 某项陈述只有部分能够得到原文支持；
- 摘要把原文较弱的表述概括成更强的表述，但尚未形成明确矛盾；
- 信息来源或归属存在明显模糊，但不足以确认发生主体颠倒；
- 某项新增内容具有一定上下文依据，但原文没有明确确认；
- 存在事实一致性风险，但无法明确指出摘要给出了一个确定的错误事实。

注意：

2分不是“存在明显事实错误”的分数。

一旦摘要存在可以明确识别的重要事实错误，应评为1分或0分。

### 1分：存在明确事实错误或明确的无依据事实

摘要部分内容可能与原文一致，但至少存在一项具有实际意义的明确事实错误，或者新增了一项原文没有支持的重要事实。

包括但不限于：

- 金额错误；
- 日期或期限发生具有实际意义的错误；
- 主体行为归属错误；
- 原告、被告或其他主体发生混淆；
- 行为、事件、对象或因果关系被错误描述；
- 将原告主张错误写成法院认定事实；
- 将被告辩称错误写成法院认定事实；
- 将法院认定事实错误归属于其他主体；
- 新增原文没有记载的重要事实；
- 法律名称、法律条文或主要法律依据出现明确错误；
- 对诉讼请求、抗辩意见、法院查明事实存在明确事实偏差。

只要存在上述明确且具有实际意义的事实错误，即使摘要其他部分正确，也原则上不得评为2分、3分或4分。

但是，如果该错误直接改变了该要素的核心含义，则应进一步评为0分。

### 0分：核心事实错误、核心矛盾或严重幻觉

摘要对当前要素的核心事实进行了错误描述，使其与原文形成明显矛盾，或者新增了严重改变案件理解的虚假事实。

包括但不限于：

- 裁判结果被反转，例如“支持”写成“驳回”，“驳回”写成“支持”；
- 主要责任承担主体发生颠倒；
- 原告和被告在核心事件中的身份或行为发生颠倒；
- 核心金额发生严重错误并改变案件主要事实；
- 将法院明确否定的事实写成法院认定成立；
- 将法院明确认定成立的核心事实写成不成立；
- 将当事人的核心主张直接写成法院已经认定，并导致案件事实性质发生变化；
- 罪名、案由、主要法律关系等核心性质发生错误；
- 裁判义务、赔偿责任、支付责任等核心裁判内容发生错误；
- 摘要虚构原文不存在的核心事实；
- 当前要素的大部分主要事实与原文不一致。

0分与1分的区别：

1分 = 摘要存在明确事实错误，但摘要对当前要素的核心含义仍基本可辨认，其他主要内容仍可能正确。

0分 = 错误已经涉及当前要素的核心事实，导致摘要对该要素的整体理解发生实质性改变。

## 六、评分优先级

评分时按照以下顺序判断：

第一步：
是否存在核心事实错误、核心矛盾或严重虚构？

如果是，评0分。

第二步：
是否存在至少一项明确且具有实际意义的事实错误或无依据的重要事实？

如果是，原则上评1分。

第三步：
是否不存在明确事实错误，但存在无法充分支持、明显语义扩大、归属模糊等实质性疑点？

如果是，评2分。

第四步：
是否只有轻微、不影响事实含义的表达偏差？

如果是，评3分。

第五步：
摘要实际陈述的所有事实是否均受到原文支持？

如果是，评4分。

不要因为摘要中同时存在大量正确事实，而抵消一个明确的重要事实错误。

例如：

摘要包含10项事实，其中9项正确、1项重要金额错误。

不能因为“90%的内容正确”而评3分或4分。

如果该金额错误属于明确且具有实际意义的事实错误，应评1分；如果属于决定当前要素含义的核心金额错误，则应评0分。

## 七、输出要求

你只能输出一个整数：

0
1
2
3
或
4

不得输出理由。
不得输出分析过程。
不得输出JSON。
不得输出任何其他文字。"""


# ---------------------------------------------------------------------------
# 少样本版判定 Prompt
# ---------------------------------------------------------------------------
# 为什么需要它：规范 Prompt 是给"能读懂一长串细则"的模型写的。实测
#
#   Qwen2.5-0.5B  三套提示词下都是常量输出（4 / 3 / 1），提示词无从下手
#   Qwen2.5-1.5B  10 条探针答对 6 条，**答案随内容变化**（pmax 0.45~1.00），
#                 但错在最要命的四条上：合理概括判 0、金额写错判 2、
#                 主体颠倒判 4、编造事实判 4
#
# 后者是"能力有、行为没锚定"，不是"能力不足" —— 这种情况示例比细则管用。
# 五个示例逐一对应上面四条失败模式，外加一条结果反转。
#
# 示例里的分数刻意只用 4 / 1 / 0 三档：五档的细分对 1.5B 太细，
# 能把"对"和"错"分开就够（探针判据也是 ≥3 / ≤1）。
JUDGE_SYSTEM_FEWSHOT = """你是裁判文书摘要事实一致性评价器。判断摘要里陈述的事实能否被原文支持。

评分：
4 = 摘要的陈述都能被原文支持。允许省略细节、换词、合理概括。
1 = 摘要里有明显错误（金额、主体、时间、行为与原文不符），或加了原文没有的内容。
0 = 摘要的核心结论与原文相反。

关键：摘要没提到的内容不算错；摘要自己加上原文没有的内容算错。

示例1（省略加概括，正确）
原文：被告于2019年3月1日向原告偿还借款人民币100000元。
摘要：被告曾偿还部分借款。
输出 4

示例2（金额写错）
原文：判决被告偿还原告借款本金50000元。
摘要：判决被告偿还原告借款本金90000元。
输出 1

示例3（主体颠倒）
原文：判决被告偿还原告借款本金50000元。
摘要：判决原告偿还被告借款本金50000元。
输出 0

示例4（加了原文没有的内容）
原文：被告向原告借款50000元，至今未还。
摘要：被告向原告借款50000元，至今未还，双方还约定由被告支付违约金20000元。
输出 1

示例5（结果反转）
原文：判决被告偿还原告借款本金50000元。
摘要：判决驳回原告的诉讼请求。
输出 0

现在判断下面这一例，只输出一个整数（0/1/2/3/4）。"""

JUDGE_VARIANTS = {"spec": JUDGE_SYSTEM, "fewshot": JUDGE_SYSTEM_FEWSHOT}


def build_judge_messages(
    element_name: str, document_element: str, candidate_element: str,
    variant: str = "spec",
) -> List[Dict[str, str]]:
    """`element_name` 用英文键名，但正文里给出中文名 —— 需求里就是这么写的。"""
    if variant not in JUDGE_VARIANTS:
        raise ValueError(f"未知的判定 Prompt 版本：{variant}（可选 {list(JUDGE_VARIANTS)}）")
    zh = ELEMENT_ZH.get(element_name, element_name)

    if variant == "fewshot":
        # **user 消息必须和示例里的格式一致。**
        # 第一版少样本没生效就是这个原因：示例写的是"原文：…/摘要：…"，
        # 而真实调用用的是规范 prompt 那套"裁判文书原文要素：…"的冗长格式，
        # 格式对不上，模型学到的是另一个任务的行为，于是坏样本全卡在 2 分。
        user = (
            f"要素：{zh}\n"
            f"原文：{document_element}\n"
            f"摘要：{candidate_element}\n"
            "只输出一个整数（0/1/2/3/4）。"
        )
        return [
            {"role": "system", "content": JUDGE_VARIANTS[variant]},
            {"role": "user", "content": user},
        ]

    user = f"""当前评价要素类型：
{zh}（{element_name}）

裁判文书原文要素：
{document_element}

待评价摘要要素：
{candidate_element}

    请判断待评价摘要要素与裁判文书原文要素的事实一致性。"""
    return [
        {"role": "system", "content": JUDGE_VARIANTS[variant]},
        {"role": "user", "content": user},
    ]
