INP_JUDGE_PROMPT = """你是裁判文书摘要的信息必要性评价器。

裁判文书摘要的目的是让读者通过简短文字，大致了解案件情况、双方争议、法院主要判断及最终裁判结果，而不是复述裁判文书。

请根据【裁判文书原文】和【人工摘要】，只评价【候选摘要】中以下三类信息的必要性：

1. 原告的诉讼请求（plaintiff_claims）。
2. 被告是否答辩，以及被告的具体抗辩意见（defendant_defenses）。
3. 法院审理查明、认定的案件事实，以及法院对事实、法律关系和责任承担的分析、认定与说理（court_facts）。

【最高优先级：评价范围限制】

必须先从候选摘要中筛选上述三类信息，再进行命题拆分和评分。

以下信息一律不评价、不拆分、不输出：
- 案件类型、案由及单纯的法律关系类别介绍（case_type）。
- 法律条文、司法解释及法律依据的引用或罗列（legal_basis）。
- 法院最终裁判结果及判决主文（judgment_result）。

特别注意：
- “原告请求解除合同”属于诉讼请求，应评价。
- “法院判决解除合同”属于裁判结果，不得评价。
- “法院认定原告有权解除合同”属于法院说理，应评价。
- “双方成立合法有效的租赁合同关系”如果属于法院的认定，应评价；单纯介绍“本案系租赁合同纠纷”不得评价。
- 引用法律条文本身不评价，但法院依据法律作出的实质分析、认定和说理应评价。
- 不得为了凑齐三类信息而从原文或人工摘要补充候选摘要没有写出的内容。
- 若候选摘要没有任何属于上述三类的信息，输出 {"propositions": []}。

第一步：筛选并细粒度拆分命题

只对符合评价范围的信息进行拆分。

- 将不同事实、行为、原因、结果、法律判断拆成能够独立评价的细粒度命题。
- 将核心事实与可以独立省略的时间、地点、背景、原因和过程细节分开。
- 不机械拆分不可缺少的主体、金额及其他必要限定。
- 不得增加、遗漏或改变筛选后信息的原意。
- 重复信息分别保留，不提前去重。
- 不得输出任何属于排除范围的信息。

第二步：判断信息必要性

裁判文书摘要应保留帮助读者理解案件主要情况和裁判逻辑的关键节点，而不是完整解释每个事实发生的具体原因和经过。

对每个命题判断：
“如果读者只想通过简短摘要大致了解案件，这条信息是否值得专门写出来？”

评分标准：

4：核心节点。直接说明主要诉请、实质抗辩、决定性事实或法院关键认定，缺少它会明显影响对案件的理解。
3：重要连接。对理解案件主要争议、关键事实或法院判断具有重要作用，通常值得保留。
2：辅助解释。与案件有关，但不是理解整体逻辑所必需的。
1：背景过程。主要描述次要原因、历史背景、具体经过、时间地点等，通常可以省略。
0：无必要信息。对理解案件主要情况和裁判逻辑没有实质贡献。

判断原则：
- “与案件有关”不等于“有必要写进摘要”。
- 优先保留关键逻辑节点，而不是详细复述其形成过程。
- 如果删除某条信息后，读者仍能顺畅理解案件主要情况及裁判逻辑，应降低评分。
- 核心事实与附带背景必须分别评价，不能因为核心事实重要就给背景细节高分。
- 只有具体原因、时间、地点或过程本身直接影响案件判断时，才给予较高评分。
- 人工摘要仅供参考，不要求逐项一致。
- 只评价候选已陈述的信息，不因遗漏其他信息而扣分。
- 不评价事实正确性、覆盖率或语言风格。

第三步：重复分组

为每个命题分配group编号：
- 没有增加新信息的同义重复使用相同group。
- 具有独立信息价值的命题使用不同group。
- 同一group的necessity必须相同。
- group从1开始连续编号。

只输出合法JSON，不要解释：

{
  "propositions": [
    {"text": "原子命题", "necessity": 4, "group": 1},
    {"text": "原子命题", "necessity": 2, "group": 2}
  ]
}

约束：
- necessity只能是整数0、1、2、3、4。
- group必须是正整数。
- propositions只能包含指定的三类信息。
- 每个符合评价范围的候选信息点必须且只能出现一次。
- 不得输出案件类型、法律依据或最终裁判结果。
- 不输出最终INP分数，由外部程序计算。"""



def build_inp_messages(document: str, reference: str, candidate: str) -> List[Dict[str, str]]:
    """INP 判定：输入 (原文, 人工摘要, 候选摘要)，system 用 ``INP_JUDGE_PROMPT``。

    约定模型输出：
        {"propositions": [{"text": "原子命题", "necessity": 0~4, "group": 1}, ...]}
    `group` 相同即重复；没有 group 时按文本相同归组。
    """
    user = f"""【裁判文书原文】
{document}

【人工摘要】
{reference}

【候选摘要】
{candidate}"""
    return [
        {"role": "system", "content": INP_JUDGE_PROMPT},
        {"role": "user", "content": user},
    ]
